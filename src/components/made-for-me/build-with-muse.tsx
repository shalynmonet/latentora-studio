import { AlertTriangle, CheckCircle2, Download, FileCode2, Hammer, Loader2, RefreshCw, XCircle } from "lucide-react";
import { useEffect, useState } from "react";
import { Badge } from "@/components/ui/badge";
import { Button } from "@/components/ui/button";
import { Panel, useBusy } from "@/components/latentora/shared";
import { buildWithMuse } from "@/lib/made-for-me.functions";
import type { BuildCheck, MuseBuild } from "@/lib/build-rules";
import type { Invention } from "@/lib/made-for-me";
import { cn } from "@/lib/utils";

const slug = (s: string) => s.toLowerCase().replace(/[^a-z0-9]+/g, "-").replace(/^-|-$/g, "") || "my-tool";

function buildInfo(b: MuseBuild) {
  const line = (c: BuildCheck) => `- [${c.status === "pass" ? "x" : " "}] ${c.label} — ${c.status.toUpperCase()}: ${c.detail}`;
  return [
    `# How this project was made`,
    ``,
    `- Tool: ${b.tool_name}`,
    `- Generated by: ${b.model} (Meta Muse Wonder) via ${b.endpoint}`,
    `- Generated: ${b.generated_at}`,
    `- Attempts: ${b.attempts}`,
    ``,
    `Latentora checked these files without running them. Static checks are not proof that the app works or is accessible — try it and the acceptance tests in README.md.`,
    ``,
    `## Automatic checks`,
    ...b.checks.map(line),
  ].join("\n");
}

async function makeZip(b: MuseBuild): Promise<Blob> {
  const { default: JSZip } = await import("jszip");
  const zip = new JSZip();
  const dir = zip.folder(slug(b.tool_name))!;
  for (const f of b.files) dir.file(f.path, f.content);
  dir.file("LATENTORA-BUILD-INFO.md", buildInfo(b));
  return zip.generateAsync({ type: "blob", compression: "DEFLATE" });
}

function downloadBlob(blob: Blob, filename: string) {
  const url = URL.createObjectURL(blob);
  const a = document.createElement("a");
  a.href = url;
  a.download = filename;
  document.body.appendChild(a);
  a.click();
  a.remove();
  setTimeout(() => URL.revokeObjectURL(url), 30_000);
}

const STAGES = [
  [0, "Sending your approved blueprint to Muse Wonder…"],
  [20, "Muse Wonder is writing the HTML, styles and app logic…"],
  [70, "Still writing — complete apps take a little while…"],
  [130, "Checking files, structure and syntax (without running the code)…"],
  [200, "Fixing anything that didn't pass, if needed…"],
] as const;

function Progress() {
  const [s, setS] = useState(0);
  useEffect(() => {
    const t = setInterval(() => setS((x) => x + 1), 1000);
    return () => clearInterval(t);
  }, []);
  const label = [...STAGES].reverse().find(([at]) => s >= at)?.[1];
  return (
    <div role="status" aria-live="polite" className="mt-5 rounded-2xl border border-border/60 p-4 text-sm">
      <div className="flex items-center gap-3">
        <Loader2 className="size-5 animate-spin text-gold" />
        <span>{label}</span>
        <span className="ml-auto tabular-nums text-muted-foreground">
          {Math.floor(s / 60)}:{String(s % 60).padStart(2, "0")}
        </span>
      </div>
      <p className="mt-2 text-xs text-muted-foreground">Usually 1–4 minutes. Keep this page open.</p>
    </div>
  );
}

function CheckRow({ c }: { c: BuildCheck }) {
  const Icon = c.status === "pass" ? CheckCircle2 : c.status === "warn" ? AlertTriangle : XCircle;
  return (
    <li className="flex items-start gap-2 text-sm">
      <Icon className={cn("mt-0.5 size-4 shrink-0", c.status === "pass" ? "text-success" : c.status === "warn" ? "text-warning" : "text-destructive")} aria-hidden />
      <span>
        <span className="sr-only">{c.status}: </span>
        {c.label} <span className="text-xs text-muted-foreground">— {c.detail}</span>
      </span>
    </li>
  );
}

export function BuildWithMuse({ workspaceId, inv, set }: { workspaceId: string; inv: Invention; set: (i: Invention) => void }) {
  const b = inv.build;
  const { busy, run } = useBusy();
  const [error, setError] = useState<string | null>(null);
  const [zip, setZip] = useState<Blob | null>(null);
  const [open, setOpen] = useState<string | null>(null);
  const stale = b && inv.blueprint && b.generated_at < inv.blueprint.generated_at;

  useEffect(() => {
    setZip(null);
    if (b) makeZip(b).then(setZip, () => setZip(null));
  }, [b]);

  const go = async () => {
    setError(null);
    let failed: string | null = null;
    const res = await run(async () => {
      try {
        return await buildWithMuse({ data: { id: workspaceId, inventionId: inv.id } });
      } catch (e) {
        failed = e instanceof Error ? e.message : "The build failed.";
        throw e;
      }
    });
    if (res) set(res);
    else setError(failed ?? "The build failed. Please try again.");
  };

  return (
    <Panel>
      <div className="flex flex-wrap items-start justify-between gap-3">
        <div className="max-w-2xl">
          <p className="eyebrow">Build with Muse</p>
          <h3 className="mt-2 text-3xl md:text-4xl">Turn this blueprint into a real app</h3>
          <p className="mt-2 text-sm text-muted-foreground">
            Muse Wonder (<code>muse-wonder-1.0</code>, Meta's coding model) writes the complete source code for a small, self-contained web app from your
            approved blueprint — only the details you approved are sent. You download it as a .zip and open it on your own device. Latentora checks the
            files but never runs them.
          </p>
        </div>
        {b && <Badge variant="live">Live · {b.model}</Badge>}
      </div>

      {!b && !busy && (
        <Button size="lg" className="mt-5" onClick={go}>
          <Hammer /> Build with Muse
        </Button>
      )}
      {busy && <Progress />}
      {error && !busy && (
        <div role="alert" className="mt-5 rounded-2xl border border-destructive/50 bg-destructive/10 p-4 text-sm">
          <p>{error}</p>
          <Button size="sm" variant="outline" className="mt-3" onClick={go}>
            <RefreshCw /> Try again
          </Button>
        </div>
      )}

      {b && !busy && (
        <div className="mt-6 space-y-6">
          {stale && (
            <p className="rounded-2xl border border-warning/40 bg-warning/10 p-3 text-sm">
              Your blueprint changed after this app was built. Rebuild to match it.
            </p>
          )}
          <div className="flex flex-wrap gap-2">
            <Button onClick={() => zip && downloadBlob(zip, `${slug(b.tool_name)}.zip`)} disabled={!zip}>
              {zip ? <Download /> : <Loader2 className="animate-spin" />} Download project (.zip)
            </Button>
            <Button variant="outline" onClick={go}>
              <RefreshCw /> Rebuild
            </Button>
          </div>
          <div className="grid gap-6 md:grid-cols-2">
            <div>
              <h4 className="text-xl">Set up in one minute</h4>
              <ol className="mt-2 list-decimal space-y-1 pl-5 text-sm text-muted-foreground">
                <li>Unzip the download.</li>
                <li>Open <code>index.html</code> in Chrome, Edge or Safari — or run <code>npx serve .</code> in the folder for full features like voice input.</li>
                <li>Read <code>README.md</code> for how to use it and the tests to try.</li>
              </ol>
              <p className="mt-3 text-xs text-muted-foreground">
                Generated {new Date(b.generated_at).toLocaleString()} by <code>{b.model}</code> via <code>{b.endpoint}</code>
                {b.attempts > 1 ? ` · repaired automatically after a first attempt failed checks` : ""}.
              </p>
            </div>
            <div>
              <h4 className="text-xl">Automatic checks</h4>
              <p className="mb-2 text-xs text-muted-foreground">Static checks only — they don't prove the app works or is accessible. Try it yourself.</p>
              <ul className="space-y-1.5">
                {b.checks.map((c) => (
                  <CheckRow key={c.id} c={c} />
                ))}
              </ul>
            </div>
          </div>
          <div>
            <h4 className="text-xl">Files</h4>
            <ul className="mt-2 space-y-2">
              {b.files.map((f) => (
                <li key={f.path} className="rounded-2xl border border-border/60">
                  <button
                    type="button"
                    className="flex w-full items-center gap-2 px-4 py-2 text-left text-sm"
                    aria-expanded={open === f.path}
                    onClick={() => setOpen(open === f.path ? null : f.path)}
                  >
                    <FileCode2 className="size-4 text-gold" aria-hidden /> {f.path}
                    <span className="ml-auto text-xs text-muted-foreground">{f.content.split("\n").length} lines</span>
                  </button>
                  {open === f.path && (
                    <pre className="max-h-96 overflow-auto border-t border-border/60 bg-background/50 p-4 text-xs">{f.content}</pre>
                  )}
                </li>
              ))}
            </ul>
          </div>
        </div>
      )}
    </Panel>
  );
}
